// Extracts the skill icons used by Gato Nightreign from game-icons.net (CC BY 3.0, via @iconify-json/game-icons).
// Run: node scripts/build-icons.mjs   (dev only; writes src/night-skill-icons.ts)
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const set=JSON.parse(await readFile(require.resolve('@iconify-json/game-icons/icons.json'),'utf8'));
const NAMES='sword-slice,crossed-swords,moon,bloody-sword,night-sky,bolt-spell-cast,sprout,heart-plus,growth,sun,axe-swing,magic-shield,round-shield,shield-bash,trident-shield,claws,vampire-dracula,dread-skull,wolf-howl,magic-swirl,death-zone,vibrating-shield,snowflake-1,ghost,crossbow,arrow-flights,tornado,cobweb,heavy-arrow,ringed-beam,beams-aura,magic-palm,pentacle,magic-portal,dodging,sprint,jump-across,meteor-impact,healing,shield-reflect,chain-lightning,ice-spell-cast,teleport'.split(',');
const icons={};const authors=new Set();
for(const name of NAMES){const icon=set.icons[name];if(!icon)throw Error('Ícone em falta: '+name);icons[name]=icon.body;}
const out=`// Generated by scripts/build-icons.mjs from game-icons.net (CC BY 3.0: Lorc, Delapouite, Skoll and contributors).
// Do not edit by hand.
export const SKILL_ICON_BODIES:Record<string,string>=${JSON.stringify(icons)};
export const skillIcon=(name:string)=>\`<svg class="gi" viewBox="0 0 ${set.width||512} ${set.height||512}" aria-hidden="true">\${SKILL_ICON_BODIES[name]||''}</svg>\`;
`;
await writeFile(new URL('../src/night-skill-icons.ts',import.meta.url),out);
console.log('src/night-skill-icons.ts',NAMES.length,'ícones',Math.round(out.length/1024)+' KB',authors.size);
