function buildClassSkillWeb(): SkillWebNodeDef[] {
  const nodes: SkillWebNodeDef[] = [];
  const classes: ArcanaClassId[] = ['chess', 'chrono', 'chaos', 'rune'];

  for (const cid of classes) {
    const cls = ARCANA_CLASSES[cid];
    // 3 ramos principais a 270° (topo), 30° (baixo-direita) e 150° (baixo-esquerda)
    const baseAngles = [-90, 30, 150];

    cls.specializations.forEach((spec, bIdx) => {
      const branch = bIdx as 0 | 1 | 2;
      const centerAngle = baseAngles[bIdx];

      // Tier 1: Iniciação da Vertente
      const n1Id = `${cid}_web_b${branch}_t1`;
      // Tier 2 Left & Right (bifurcação na teia)
      const n2aId = `${cid}_web_b${branch}_t2a`;
      const n2bId = `${cid}_web_b${branch}_t2b`;
      // Tier 3: Maestria da Vertente
      const n3Id = `${cid}_web_b${branch}_t3`;
      // Tier 4: Ascensão Suprema da Vertente
      const n4Id = `${cid}_web_b${branch}_t4`;
      // Ponte lateral para o próximo ramo
      const nextBranch = ((bIdx + 1) % 3) as 0 | 1 | 2;
      const bridgeTargetId = `${cid}_web_b${nextBranch}_t2a`;

      const classCards = ARCANA_UPGRADES.filter(u => u.classRestriction === cid);
      const evoCard = classCards.find(u => u.category === 'evolution') || ARCANA_UPGRADES[0];
      const cCard1 = classCards[bIdx % Math.max(1, classCards.length)] || ARCANA_UPGRADES[0];

      nodes.push(
        {
          id: n1Id,
          classId: cid,
          branchIndex: branch,
          tier: 1,
          angleDeg: centerAngle,
          radiusPct: 26,
          name: spec.keyNodes[0] || spec.name,
          subBendingName: spec.name,
          icon: spec.icon,
          description: `Desperta a ${spec.name}: ${spec.description}`,
          visualEffectDesc: 'Ativa a aura elemental da vertente ao redor do teu personagem.',
          costPoints: 1,
          connectsTo: [n2aId, n2bId],
          upgradeId: cCard1.id,
        },
        {
          id: n2aId,
          classId: cid,
          branchIndex: branch,
          tier: 2,
          angleDeg: centerAngle - 18,
          radiusPct: 48,
          name: spec.keyNodes[1] || `Fluxo de ${spec.name}`,
          subBendingName: spec.name,
          icon: '✦',
          description: `Amplifica a ${spec.name} com +22% de potência, maior alcance de impacto e partículas densas.`,
          visualEffectDesc: 'Adiciona trilhas secundárias e ondas de choque aos golpes desta vertente.',
          costPoints: 1,
          connectsTo: [n3Id, bridgeTargetId],
          upgradeId: 'fund_arcane_edge',
        },
        {
          id: n2bId,
          classId: cid,
          branchIndex: branch,
          tier: 2,
          angleDeg: centerAngle + 18,
          radiusPct: 48,
          name: `Cadência: ${spec.subtitle.split('&')[0]}`,
          subBendingName: spec.name,
          icon: '⚡',
          description: `Acelera a conjuração da ${spec.name} em +18% e reduz o tempo de recarga das técnicas.`,
          visualEffectDesc: 'Aumenta a velocidade das animações marciais e reduz o intervalo entre técnicas.',
          costPoints: 1,
          connectsTo: [n3Id],
          upgradeId: 'fund_swift_conduit',
        },
        {
          id: n3Id,
          classId: cid,
          branchIndex: branch,
          tier: 3,
          angleDeg: centerAngle,
          radiusPct: 68,
          name: spec.keyNodes[2] || `Mestre de ${spec.name}`,
          subBendingName: spec.name,
          icon: spec.icon,
          description: `Domínio completo de ${spec.name}: +1 Projétil/Onda adicional e reação elemental em cadeia.`,
          visualEffectDesc: 'Duplica as manifestações visuais da vertente no campo de batalha.',
          costPoints: 2,
          connectsTo: [n4Id],
          upgradeId: 'mod_twin_cast',
        },
        {
          id: n4Id,
          classId: cid,
          branchIndex: branch,
          tier: 4,
          angleDeg: centerAngle,
          radiusPct: 86,
          name: `Ascensão: ${spec.name}`,
          subBendingName: spec.name,
          icon: '👑',
          description: evoCard.shortDesc,
          visualEffectDesc: evoCard.behaviorTransformation,
          costPoints: 3,
          connectsTo: [],
          upgradeId: evoCard.id,
        }
      );
    });
  }

  return nodes;
}

